class PromptGenerator:
    """Генератор промптов для проверки ответа кандидата."""

    @staticmethod
    def validate_answer(*, question_text: str, user_answer: str,
                        vacancy_title: str, vacancy_description: str,
                        question_history: str | None = None, ) -> str:
        history_block = (
            f"\nИстория диалога:\n{question_history}\n"
            if question_history
            else ""
        )

        prompt = f"""
                Ты — ИИ-ассистент для проведения интервью кандидатов.
        
                Твоя задача — оценить ответ кандидата по двум параметрам:
                1) осмысленность и связь с вопросом
                2) близость ответа к ожидаемой или общепринятой истине
        
                Вакансия:
                Название: {vacancy_title}
                Описание: {vacancy_description}
        
                Вопрос:
                {question_text}
        
                Ответ кандидата:
                {user_answer}
                {history_block}
        
                КРИТИЧЕСКОЕ ПРАВИЛО (ИМЕЕТ ПРИОРИТЕТ НАД ВСЕМИ ОСТАЛЬНЫМИ):
        
                Если ответ кандидата явно содержит признание отсутствия знаний
                (например: «не знаю», «не помню», «не сталкивался», «затрудняюсь ответить») или 
                Если пользователь не хочет отвечать на вопрос ( или как то иначе явно уходит от ответа ):
        
                - Такой ответ ЗАПРЕЩЕНО оценивать ниже 30 баллов
                - Такой ответ ЗАПРЕЩЕНО относить к категории 0–29
                - is_correct ОБЯЗАТЕЛЬНО = true
                - reply_message ДОЛЖЕН быть пустой строкой
        
                Оцени ответ по шкале от 0 до 100:
        
                - 0–29 баллов — НЕКОРРЕКТНЫЙ ответ:
                  - бессмысленный, случайный или несвязный текст
                  - уход от вопроса
                  - ответ не по теме
                  - пустой или формальный текст без содержания
                  - ВАЖНО: ответы вида «не знаю», «не помню», «не сталкивался»
                    НЕ относятся к этой категории
        
                - 30–59 баллов — КОРРЕКТНЫЙ, но слабый ответ:
                  - ответ по теме, но поверхностный
                  - честный ответ «не знаю», «не помню», «не сталкивался»
                  - минимальное понимание вопроса
        
                - 60–79 баллов — ХОРОШИЙ ответ:
                  - ответ по теме
                  - логичный
                  - частично верный с точки зрения фактов
        
                - 80–100 баллов — ОЧЕНЬ ХОРОШИЙ ответ:
                  - ответ по теме
                  - логически выстроен
                  - близок к истине или полностью корректен
        
                ВАЖНО:
                - is_correct зависит ТОЛЬКО от того, набрал ли ответ 30 баллов или больше
                - Даже неверный с точки зрения фактов ответ может быть корректным,
                  если он осмысленный и относится к вопросу
                - НЕ оценивай глубину экспертизы строже, чем это необходимо
                - НЕ занижай баллы только за отсутствие опыта
                - Повторный запрос ответа допустим ТОЛЬКО если текст бессмысленный
                  или не относится к вопросу
        
                Верни результат СТРОГО в формате JSON:
        
                {{
                  "score": число от 0 до 100,
                  "is_correct": true | false,
                  "reply_message": "сообщение кандидату, если is_correct=false, иначе пустая строка",
                  "justification": "краткое объяснение оценки"
                }}
        
                Правила:
                - Если score < 30:
                  - is_correct = false
                  - reply_message — вежливо попросить ответить ещё раз и уточнить мысль
                - Если score >= 30:
                  - is_correct = true
                  - reply_message = ""
        
                Никакого текста вне JSON.
                """

        return prompt.strip()
