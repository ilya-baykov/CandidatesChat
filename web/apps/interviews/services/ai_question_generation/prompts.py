class PromptGenerator:
    """Генератор промптов для подготовки интервью."""

    @staticmethod
    def generate_questions(*,
                           vacancy_title: str,
                           vacancy_description: str,
                           candidate_resume: str,
                           questions_count: int) -> str:
        prompt = f"""
                Ты — ИИ-ассистент рекрутера.
                
                Твоя задача — подготовить уточняющие вопросы для интервью с кандидатом
                на основе его резюме и описания вакансии.
                
                Цель вопросов:
                - лучше понять реальный опыт кандидата
                - уточнить стаж, стек, зоны ответственности
                - выявить глубину участия в проектах
                - понять соответствие вакансии
                
                Вакансия:
                Название: {vacancy_title}
                Описание:
                {vacancy_description}
                
                Резюме кандидата:
                {candidate_resume}
                
                Требования к вопросам:
                - вопросы НЕ должны быть теоретическими
                - вопросы НЕ должны быть экзаменационными
                - вопросы должны касаться:
                  - опыта работы
                  - используемого стека
                  - проектов и задач
                  - ответственности и роли кандидата
                - каждый вопрос — один смысл
                - вопросы идут от общего к более детальному
                - без нумерации в тексте вопроса
                
                Сформируй {questions_count} вопросов.
                
                Верни результат строго в JSON формате:
                
                {{
                  "questions": [
                    {{ "order": 1, "text": "..." }},
                    {{ "order": 2, "text": "..." }}
                  ]
                }}
                
                Никакого текста вне JSON.
                """.strip()

        return prompt
